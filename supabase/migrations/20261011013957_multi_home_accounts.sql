create function public.create_household(p_user uuid,p_email text,p_name text,p_address text,p_member_name text,p_participates boolean)
returns integer language plpgsql security invoker set search_path='' as $$
declare h integer; mail text; today date:=(now() at time zone 'Australia/Melbourne')::date;
begin
 -- Identity and confirmed email are verified by getUser in the server-only API.
 mail=lower(p_email);
 if mail is null or length(mail)>254 or position('@' in mail)=0 then raise exception 'Verified sign in required'; end if;
 perform pg_advisory_xact_lock(hashtext('create-home:'||p_user::text));
 if (select count(*) from public.households where owner_id=p_user)>=20 then raise exception 'Property limit reached'; end if;
 if exists(select 1 from public.households where owner_id=p_user and created_at>now()-interval '10 seconds') then raise exception 'Wait a moment before adding another property'; end if;
 if length(trim(p_address)) not between 5 and 240 then raise exception 'Enter the property address'; end if;
 insert into public.households(name,address,owner_id) values(trim(p_name),trim(p_address),p_user) returning id into h;
 insert into public.members(household_id,user_id,name,email,role,position,color,participates)
 values(h,p_user,trim(p_member_name),mail,'admin',0,'#dce9ff',p_participates);
 insert into public.household_settings(id,daily_start,weekly_start,daily_tasks,weekly_tasks,cleaning_areas,reminders_enabled)
 values(h,today,today+((8-extract(isodow from today)::integer)%7),'{}','{}','{}',false);
 return h;
end $$;

create function public.accept_tenant_invitation(p_user uuid,p_email text,p_hash text)
returns integer language plpgsql security invoker set search_path='' as $$
declare invitation public.tenant_invitations; mail text; slot integer;
begin
 -- Identity and confirmed email are verified by getUser in the server-only API.
 mail=lower(p_email);
 if mail is null or length(mail)>254 or position('@' in mail)=0 then raise exception 'Verified sign in required'; end if;
 select * into invitation from public.tenant_invitations where token_hash=p_hash for update;
 if invitation.id is null or invitation.email<>mail then raise exception 'Sign in with the email this invitation was sent to'; end if;
 if invitation.accepted_at is not null then
   if exists(select 1 from public.members where household_id=invitation.household_id and user_id=p_user) then return invitation.household_id; end if;
   raise exception 'Invitation already used';
 end if;
 if invitation.expires_at<now() or invitation.revoked_at is not null then raise exception 'Invitation expired or revoked; ask your admin for a new link'; end if;
 perform 1 from public.households where id=invitation.household_id for update;
 if exists(select 1 from public.members where household_id=invitation.household_id and email=mail and user_id is not null and user_id<>p_user) then raise exception 'Account mismatch'; end if;
 select coalesce(max(position)+1,0) into slot from public.members where household_id=invitation.household_id;
 if slot>49 then raise exception 'This home has reached its member limit'; end if;
 insert into public.members(household_id,user_id,name,email,role,position,color,participates)
 values(invitation.household_id,p_user,invitation.name,mail,'member',slot,'#e4e9ef',true)
 on conflict(household_id,email) do update set user_id=p_user;
 update public.tenant_invitations set accepted_at=now() where id=invitation.id;
 -- New members join future unstarted rotations. History and started work stay intact.
 delete from public.assignments a where household_id=invitation.household_id and date>(now() at time zone 'Australia/Melbourne')::date
 and not exists(select 1 from public.submissions s where s.assignment_id=a.id)
 and not exists(select 1 from public.email_jobs j where j.assignment_id=a.id);
 return invitation.household_id;
end $$;

-- Reject cross-home assignees even when a server programming mistake occurs.
create function public.check_assignment_household() returns trigger language plpgsql security invoker set search_path='' as $$
begin
 if (select count(*) from public.members where id=any(new.member_ids) and household_id=new.household_id and participates)<>cardinality(new.member_ids)
 then raise exception 'Assignees must be participating tenants of this home'; end if;
 return new;
end $$;
create trigger assignment_household before insert or update of member_ids,household_id on public.assignments for each row execute function public.check_assignment_household();

create or replace function public.set_assignment_bin_duty()
returns trigger language plpgsql security invoker set search_path='' as $$
begin
 if new.kind='daily' and new.date>=(now() at time zone 'Australia/Melbourne')::date
 and exists(select 1 from public.household_settings where id=new.household_id and council_bins_enabled)
 and not exists(select 1 from public.submissions where assignment_id=new.id) then
 new.tasks=public.daily_tasks_for_date(new.tasks,new.date); end if;
 return new;
end $$;

create function public.save_household_settings(p_household integer,p_daily text[],p_weekly text[],p_evening integer,p_morning integer,p_deadline integer,p_enabled boolean)
returns void language plpgsql security invoker set search_path='' as $$
begin
 update public.household_settings set daily_tasks=p_daily,weekly_tasks=p_weekly,evening_hour=p_evening,morning_hour=p_morning,deadline_hour=p_deadline,reminders_enabled=p_enabled,
 cleaning_areas=array(select distinct split_part(t,': ',1) from unnest(p_weekly) t) where id=p_household;
 perform 1 from public.assignments where household_id=p_household and date>(now() at time zone 'Australia/Melbourne')::date order by id for update;
 update public.assignments a set tasks=case when a.kind='daily' then p_daily else p_weekly end
 where a.household_id=p_household and a.date>(now() at time zone 'Australia/Melbourne')::date and not exists(select 1 from public.submissions s where s.assignment_id=a.id);
end $$;
-- Keep old deployment safely scoped during rollout.
create or replace function public.save_settings(p_daily text[],p_weekly text[],p_evening integer,p_morning integer,p_deadline integer,p_enabled boolean)
returns void language sql security invoker set search_path='' as $$
 select public.save_household_settings(1,p_daily,p_weekly,p_evening,p_morning,p_deadline,p_enabled);
$$;
